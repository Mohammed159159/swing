%STARTUP Initialize MATLAB path and base workspace for the Furuta pendulum project.
%   Auto-executes when MATLAB starts in the repository root, or call `startup`
%   manually from anywhere once on the path.
%
%   Actions:
%     1. Adds project code, simulation, digital-twin, control, and test folders
%        to the MATLAB path (never calls restoredefaultpath).
%     2. Populates `params`, `plant`, and `gains` in the workspace if not already
%        present, preserving any user-modified overrides.

startup_repoRoot_ = fileparts(mfilename('fullpath'));

startup_relDirs_ = { ...
    'config', ...
    fullfile('sim', 'runners'), ...
    fullfile('sim', 'scenarios'), ...
    fullfile('digital-twin', 'validation'), ...
    fullfile('digital-twin', 'models', 'analytical'), ...
    fullfile('digital-twin', 'models', 'simscape'), ...
    fullfile('digital-twin', 'models', 'simscape', 'stl'), ...
    'control', ...
    fullfile('control', 'controllers'), ...
    fullfile('control', 'controllers', 'classical', 'pid'), ...
    fullfile('control', 'controllers', 'classical', 'pole_placement'), ...
    fullfile('control', 'controllers', 'optimal', 'lqr'), ...
    fullfile('control', 'controllers', 'swingup'), ...
    fullfile('control', 'evaluation', 'stability'), ...
    fullfile('control', 'evaluation', 'performance'), ...
    fullfile('control', 'stateflow'), ...
    'tests' ...
};

for startup_k_ = 1:numel(startup_relDirs_)
    startup_dir_ = fullfile(startup_repoRoot_, startup_relDirs_{startup_k_});
    if exist(startup_dir_, 'dir')
        addpath(startup_dir_);
    end
end

if ~exist('params', 'var')
    params = load_parameters();
end
if ~exist('plant', 'var')
    plant = build_plant(params);
end
if ~exist('gains', 'var')
    gains = compute_gains(plant, params);
end

fprintf('[Furuta] Workspace initialized (Ts = %.1f ms, V_max = %.1f V, gains ready).\n', ...
    params.Ts * 1e3, params.V_max);

clear startup_repoRoot_ startup_relDirs_ startup_k_ startup_dir_
