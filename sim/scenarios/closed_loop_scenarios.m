function S = closed_loop_scenarios(params)
%CLOSED_LOOP_SCENARIOS Standardized Phase 2 closed-loop benchmark scenarios.
%   S = CLOSED_LOOP_SCENARIOS(params) returns a catalog of closed-loop
%   simulation scenarios parameterized by params.Ts so linear, nonlinear ODE,
%   and Simscape Multibody controller evaluations share identical initial
%   conditions, references, and time grids.
%
%   Locked State Convention:
%       x0 = [theta0; dtheta0; theta1; dtheta1]  (global coordinates [rad, rad/s])
%       theta1 = 0  -> upright apex
%       theta1 = pi -> hanging downward rest
%
%   Scenarios returned:
%     Stabilizing benchmark suite:
%       S.upright_disturbance_10deg   - Initial 10 deg upright deflection  (4.0 s)
%       S.upright_impulse_disturbance - Pendulum tap dtheta1(0) = 2.5 rad/s (4.0 s)
%       S.upright_arm_step            - 30 deg arm angle setpoint step     (5.0 s)
%       S.upright_large_20deg         - Large 20 deg capture-edge recovery (4.0 s)
%     Swing-up scenario (for Phase 3 Stateflow integration):
%       S.swingup_from_rest           - Hanging rest [0; 0; pi; 0]         (6.0 s)

    if nargin < 1 || isempty(params)
        params = load_parameters();
    end
    if ~isstruct(params) || ~isfield(params, 'Ts') || ~isscalar(params.Ts) || ~(params.Ts > 0)
        error('Furuta:InvalidParameters', 'params.Ts must be a positive scalar sample time.');
    end

    dt = params.Ts;

    S.upright_disturbance_10deg = makeScenario( ...
        'upright_disturbance_10deg', ...
        'Upright Recovery (10 deg Disturbance)', ...
        [0; 0; deg2rad(10); 0], ...
        [0; 0; 0; 0], ...
        buildTimeGrid(4.0, dt), ...
        "disturbance", ...
        {'pid', 'pole_placement', 'lqr'}, ...
        'Primary upright disturbance recovery benchmark across PID, Pole Placement, and LQR.');

    S.upright_impulse_disturbance = makeScenario( ...
        'upright_impulse_disturbance', ...
        'Impulse Tap Rejection (dtheta1(0) = 2.5 rad/s)', ...
        [0; 0; 0; 2.5], ...
        [0; 0; 0; 0], ...
        buildTimeGrid(4.0, dt), ...
        "impulse", ...
        {'pid', 'pole_placement', 'lqr'}, ...
        'Repeatable angular-velocity impulse disturbance evaluating peak deflection and recovery time.');

    S.upright_arm_step = makeScenario( ...
        'upright_arm_step', ...
        'Arm Setpoint Tracking (theta0_ref = 30 deg)', ...
        [0; 0; 0; 0], ...
        [deg2rad(30); 0; 0; 0], ...
        buildTimeGrid(5.0, dt), ...
        "arm_step", ...
        {'pole_placement', 'lqr'}, ...
        'Arm reference tracking for full-state controllers exposing upright non-minimum-phase inverse response.');

    S.upright_large_20deg = makeScenario( ...
        'upright_large_20deg', ...
        'Large-Angle Stress Test (20 deg Deflection)', ...
        [0; 0; deg2rad(20); 0], ...
        [0; 0; 0; 0], ...
        buildTimeGrid(4.0, dt), ...
        "disturbance", ...
        {'pid', 'pole_placement', 'lqr'}, ...
        'Capture-boundary nonlinear and actuator saturation stress test across all 3 stabilizing controllers.');

    S.swingup_from_rest = makeScenario( ...
        'swingup_from_rest', ...
        'Standalone Energy Swing-Up from Hanging Rest', ...
        [0; 0; pi; 0], ...
        [0; 0; 0; 0], ...
        buildTimeGrid(6.0, dt), ...
        "swingup", ...
        {'swingup'}, ...
        'Astrom-Furuta energy pump reachability into capture basin (|th1|<15 deg, |dth1|<2.5 rad/s).');
end

function sc = makeScenario(id, name, x0, x_ref, t_grid, kind, controllers, desc)
    sc = struct( ...
        'id',          id, ...
        'name',        name, ...
        'x0',          x0(:), ...
        'x_ref',       x_ref(:), ...
        't_grid',      t_grid(:), ...
        'kind',        kind, ...
        'controllers', {controllers}, ...
        'description', desc);
end

function t_grid = buildTimeGrid(t_end, dt)
    nSteps = round(t_end / dt);
    t_grid = (0:nSteps).' * dt;
    if abs(t_grid(end) - t_end) > 1e-12
        t_grid(end) = t_end;
    end
end
