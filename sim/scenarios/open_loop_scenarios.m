function S = open_loop_scenarios(params)
%OPEN_LOOP_SCENARIOS Standardized Phase 1 open-loop validation scenario catalog.
%   S = OPEN_LOOP_SCENARIOS(params) returns a struct of 9 open-loop simulation
%   scenarios (5 downward + 4 upright mirror scenarios) parameterized by
%   params.Ts so analytical validation and Simscape cross-validation run on the
%   exact same time grids, initial conditions, and voltage profiles.
%
%   Locked State Convention:
%       x0 = [theta0; dtheta0; theta1; dtheta1]  (global coordinates [rad, rad/s])
%       theta1 = 0  -> upright apex
%       theta1 = pi -> hanging downward rest
%
%   Scenarios returned:
%     Downward equilibrium (theta1_eq = pi):
%       S.decay_small        - Free decay from pi + 5 deg  (6.0 s, Va = 0 V)
%       S.decay_large        - Free decay from pi + 60 deg (6.0 s, Va = 0 V)
%       S.step_small         - Small voltage step          (2.0 s, Va = 0.2 V)
%       S.step_1V            - Phase 1 open-loop 1 V step  (2.0 s, Va = 1.0 V)
%       S.step_2V            - Phase 1 open-loop 2 V step  (2.0 s, Va = 2.0 V)
%     Upright equilibrium (theta1_eq = 0, mirror suite):
%       S.upright_fall_small - Free topple from +2 deg     (0.25 s, Va = 0 V)
%       S.upright_fall_large - Extended topple from +2 deg (0.60 s, Va = 0 V)
%       S.upright_step_small - Small upright voltage step  (0.25 s, Va = 0.2 V)
%       S.upright_step_1V    - Large upright voltage step  (0.30 s, Va = 1.0 V)

    if nargin < 1 || isempty(params)
        params = load_parameters();
    end
    if ~isstruct(params) || ~isfield(params, 'Ts') || ~isscalar(params.Ts) || ~(params.Ts > 0)
        error('Furuta:InvalidParameters', 'params.Ts must be a positive scalar sample time.');
    end

    dt = params.Ts;

    % --- Downward Equilibrium Scenarios (theta1_eq = pi) ---
    S.decay_small = makeScenario( ...
        'decay_small', ...
        'Downward Free Decay (5 deg)', ...
        'downward', ...
        [0; 0; pi + deg2rad(5); 0], ...
        buildTimeGrid(6.0, dt), ...
        0.0, ...
        1.0, 3.0, ...
        'Small-angle unforced hanging decay verifying linear-vs-nonlinear match (< 1% NRMSE) and log-decrement damping.');

    S.decay_large = makeScenario( ...
        'decay_large', ...
        'Downward Free Decay (60 deg)', ...
        'downward', ...
        [0; 0; pi + deg2rad(60); 0], ...
        buildTimeGrid(6.0, dt), ...
        0.0, ...
        NaN, 3.0, ...
        'Large-angle unforced hanging decay exposing gravitational softening and nonlinear period elongation.');

    S.step_small = makeScenario( ...
        'step_small', ...
        'Downward Voltage Step (0.2 V)', ...
        'downward', ...
        [0; 0; pi; 0], ...
        buildTimeGrid(2.0, dt), ...
        0.2, ...
        1.0, 3.0, ...
        'Small-signal open-loop voltage step verifying downward linear-vs-nonlinear input coupling (< 1% NRMSE).');

    S.step_1V = makeScenario( ...
        'step_1V', ...
        'Downward Voltage Step (1.0 V)', ...
        'downward', ...
        [0; 0; pi; 0], ...
        buildTimeGrid(2.0, dt), ...
        1.0, ...
        NaN, 3.0, ...
        'Phase 1 open-loop 1 V step showing coupled arm-pendulum acceleration and onset of 3D centrifugal flinging.');

    S.step_2V = makeScenario( ...
        'step_2V', ...
        'Downward Voltage Step (2.0 V)', ...
        'downward', ...
        [0; 0; pi; 0], ...
        buildTimeGrid(2.0, dt), ...
        2.0, ...
        NaN, 3.0, ...
        'Phase 1 open-loop 2 V step showcasing strong 3D centrifugal flinging at sustained arm velocity.');

    % --- Upright Equilibrium Mirror Scenarios (theta1_eq = 0) ---
    S.upright_fall_small = makeScenario( ...
        'upright_fall_small', ...
        'Upright Free Topple (2 deg, 0.25 s)', ...
        'upright', ...
        [0; 0; deg2rad(2); 0], ...
        buildTimeGrid(0.25, dt), ...
        0.0, ...
        1.0, 3.0, ...
        'Small-angle upright topple verifying linear-vs-nonlinear match (< 1% NRMSE) and unstable RHP pole growth rate.');

    S.upright_fall_large = makeScenario( ...
        'upright_fall_large', ...
        'Upright Free Topple Breakdown (2 deg, 0.60 s)', ...
        'upright', ...
        [0; 0; deg2rad(2); 0], ...
        buildTimeGrid(0.60, dt), ...
        0.0, ...
        NaN, 3.0, ...
        'Extended upright topple showing linear exponential blow-up vs. true nonlinear free fall and capture envelope.');

    S.upright_step_small = makeScenario( ...
        'upright_step_small', ...
        'Upright Voltage Step (0.2 V, 0.25 s)', ...
        'upright', ...
        [0; 0; 0; 0], ...
        buildTimeGrid(0.25, dt), ...
        0.2, ...
        1.0, 3.0, ...
        'Small-signal upright step verifying inverted B4 < 0 input-coupling sign flip and linear agreement (< 1% NRMSE).');

    S.upright_step_1V = makeScenario( ...
        'upright_step_1V', ...
        'Upright Voltage Step (1.0 V, 0.30 s)', ...
        'upright', ...
        [0; 0; 0; 0], ...
        buildTimeGrid(0.30, dt), ...
        1.0, ...
        NaN, 3.0, ...
        'Large-signal upright step showing nonlinear departure once pendulum swings past ~20 deg.');
end

function sc = makeScenario(id, name, eq, x0, t_grid, u_spec, linGatePct, simscapeGatePct, desc)
    sc = struct( ...
        'id',                id, ...
        'name',              name, ...
        'equilibrium',       string(eq), ...
        'x0',                x0(:), ...
        't_grid',            t_grid(:), ...
        'u_spec',            u_spec, ...
        'nrmse_gate_pct',    linGatePct, ...
        'simscape_gate_pct', simscapeGatePct, ...
        'description',       desc);
end

function t_grid = buildTimeGrid(t_end, dt)
    nSteps = round(t_end / dt);
    t_grid = (0:nSteps).' * dt;
    if abs(t_grid(end) - t_end) > 1e-12
        t_grid(end) = t_end;
    end
end
