function S = closed_loop_scenarios(params)
%CLOSED_LOOP_SCENARIOS Standardized Phase 2 controller design scenarios.
%   S = CLOSED_LOOP_SCENARIOS(params) returns a catalog of closed-loop
%   simulation scenarios parameterized by params.Ts so analytical ODE and
%   Simscape Multibody controller evaluations share identical initial
%   conditions, references, and time grids.
%
%   Locked State Convention:
%       x0 = [theta0; dtheta0; theta1; dtheta1]  (global coordinates [rad, rad/s])
%       theta1 = 0  -> upright apex
%       theta1 = pi -> hanging downward rest
%
%   Scenarios returned:
%     S.upright_disturbance_10deg - Upright recovery from 10 deg deflection (4.0 s)
%     S.upright_arm_offset        - Upright balance with 30 deg arm offset  (5.0 s)
%     S.swingup_from_rest         - Standalone swing-up reachability check  (6.0 s)
%     S.full_swingup_catch        - Full swing-up -> stabilize handoff      (6.0 s)

    if nargin < 1 || isempty(params)
        params = load_parameters();
    end
    if ~isstruct(params) || ~isfield(params, 'Ts') || ~isscalar(params.Ts) || ~(params.Ts > 0)
        error('Furuta:InvalidParameters', 'params.Ts must be a positive scalar sample time.');
    end

    dt = params.Ts;

    S.upright_disturbance_10deg = makeScenario( ...
        'upright_disturbance_10deg', ...
        'Upright Recovery (10 deg Disturbance)', ...
        [0; 0; deg2rad(10); 0], ...
        [0; 0; 0; 0], ...
        buildTimeGrid(4.0, dt), ...
        'stabilize', ...
        'Primary upright disturbance recovery test across PID, Pole Placement, and LQR.');

    S.upright_arm_offset = makeScenario( ...
        'upright_arm_offset', ...
        'Upright Arm-Centering (30 deg Arm, 5 deg Pendulum)', ...
        [deg2rad(30); 0; deg2rad(5); 0], ...
        [0; 0; 0; 0], ...
        buildTimeGrid(5.0, dt), ...
        'stabilize', ...
        'Verifies simultaneous upright stabilization and arm-angle recentering to theta0 = 0.');

    S.swingup_from_rest = makeScenario( ...
        'swingup_from_rest', ...
        'Standalone Energy Swing-Up from Hanging Rest', ...
        [0; 0; pi; 0], ...
        [0; 0; 0; 0], ...
        buildTimeGrid(6.0, dt), ...
        'swingup', ...
        'Verifies Astrom-Furuta energy pump drives pendulum into capture zone (|th1|<15 deg, |dth1|<2.5 rad/s).');

    S.full_swingup_catch = makeScenario( ...
        'full_swingup_catch', ...
        'Full Swing-Up & Capture Handoff (Auto-Catch Preview)', ...
        [0; 0; pi; 0], ...
        [0; 0; 0; 0], ...
        buildTimeGrid(6.0, dt), ...
        'auto_catch', ...
        'End-to-end swing-up from hanging rest into capture handoff and upright balance.');
end

function sc = makeScenario(id, name, x0, x_ref, t_grid, defaultMode, desc)
    sc = struct( ...
        'id',           id, ...
        'name',         name, ...
        'x0',           x0(:), ...
        'x_ref',        x_ref(:), ...
        't_grid',       t_grid(:), ...
        'default_mode', string(defaultMode), ...
        'description',  desc);
end

function t_grid = buildTimeGrid(t_end, dt)
    nSteps = round(t_end / dt);
    t_grid = (0:nSteps).' * dt;
    if abs(t_grid(end) - t_end) > 1e-12
        t_grid(end) = t_end;
    end
end
